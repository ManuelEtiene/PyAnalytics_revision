# 2: EXTRAÇÃO DE DADOS DO PDF
pdf_path = "remume_versao_2024.pdf"

lista_tabelas = []

try:
    # Abrindo o arquivo PDF
    with pdfplumber.open(pdf_path) as pdf:
        total_paginas = len(pdf.pages)
        print(f"O arquivo possui {total_paginas} páginas.")

        # Percorrendo página por página
        for i, pagina in enumerate(pdf.pages):
            tabelas_da_pagina = pagina.extract_tables()

            for tabela in tabelas_da_pagina:
                # Converte a tabela encontrada na página para DataFrame temporário
                df_temp = pd.DataFrame(tabela)
                lista_tabelas.append(df_temp)

            # Print para acompanhar o progresso em PDFs muito longos
            if (i + 1) % 5 == 0 or (i + 1) == total_paginas:
                print(f"Progressos: {i + 1}/{total_paginas} páginas processadas.")

    # Consolidando todas as páginas em um único DataFrame bruto
    if lista_tabelas:
        df_remume_bruto = pd.concat(lista_tabelas, ignore_index=True)

        print("\n Formato dos Dados Brutos extraídos (Primeiras linhas):")
        print(df_remume_bruto.head())
    else:
        print("Nenhuma tabela estruturada foi encontrada no PDF. Verifique se o arquivo")
        df_remume_bruto = pd.DataFrame()

except FileNotFoundError:
    print(f"ERRO NO PASSO 2: O arquivo '{pdf_path}' não foi encontrado.")
    print("Por favor, clique no ícone de pasta na barra esquerda do Colab e faça o upload do PDF com esse nome exato.")
    df_remume_bruto = pd.DataFrame()

print("-" * 50)

# PASSO 3: TRATAMENTO, LIMPEZA E FORMATAÇÃO AVANÇADA DOS DADOS

if not df_remume_bruto.empty:
    # 1. Faz uma cópia de segurança
    df_limpo = df_remume_bruto.copy()

    # 2. Promove a linha index 0 (que contém os nomes reais) para ser o cabeçalho
    df_limpo.columns = df_limpo.iloc[0]
    df_limpo = df_limpo[1:].reset_index(drop=True)

    # 3. Limpeza dos títulos das colunas (remove quebras de linha e espaços)
    df_limpo.columns = [str(col).replace('\n', ' ').strip() for col in df_limpo.columns]

    # 4. Remove colunas que tenham nomes inválidos (como 'None' ou 'nan')
    colunas_validas = [col for col in df_limpo.columns if col not in ['None', 'nan', '', 'NaN']]
    df_limpo = df_limpo[colunas_validas]

    # 5. Remove linhas onde os campos cruciais são nulos ou strings vazias
    df_limpo = df_limpo.dropna(subset=['Item', 'Medicamento'])

    # 6.Mantém apenas linhas onde o 'Item' começa com um número (01, 02...)
    # Usamos uma expressão regular (regex) simples para evitar travar o Pandas
    df_limpo = df_limpo[df_limpo['Item'].astype(str).str.contains(r'^\d+')]

    # 7. Limpa o caractere '\n' de dentro de todas as células de texto
    for col in df_limpo.columns:
        df_limpo[col] = df_limpo[col].astype(str).str.replace('\n', ' ').str.strip()

    # Reset do índice para ficar linear (0, 1, 2...)
    df_limpo = df_limpo.reset_index(drop=True)

    print(f"\n Total de medicamentos válidos catalogados: {len(df_limpo)}")
    print("\n" + "="*50)
    print("VISUALIZAÇÃO DOS DADOS TRATADOS")
    print("="*50)

    # Configurações de exibição otimizadas para o Google Colab
    pd.set_option('display.max_columns', None)
    pd.set_option('display.max_colwidth', None)
    pd.set_option('display.width', 1000)

    # Exibe os 15 primeiros medicamentos perfeitamente alinhados
    print(df_limpo.head(15))

    # Exportação
    df_limpo.to_csv("remume_limpa_2024.csv", index=False)
    print("\n Arquivo 'remume_limpa_2024.csv' gerado com sucesso!")

else:
    print("Passo 3 interrompido: O DataFrame bruto está vazio.")